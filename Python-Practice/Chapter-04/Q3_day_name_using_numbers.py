days = int(input("Please Enter a number in the range [1:7] to get the day: "))

if days == 1:
    print("Day 1 is Monday")
elif days == 2:
    print("Day 2 is Tuesday")
elif days == 3:
    print("Day 3 is Wednesday")
elif days == 4:
    print("Day 4 is Thursday")
elif days == 5:
    print("Day 5 is Friday")
elif days == 6:
    print("Day 6 is Saturday")
elif days == 7:
    print("Day 7 is Sunday")
else:
    print("Please enter a valid number in the range [1:7]")